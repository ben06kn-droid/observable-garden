// Write public/examples/grove.json: the home page's birches, drawn from the restart example's logged
// search (public/examples/overview-tree.json) by src/birch.ts, with every twig and leaf already placed.
// The placement search runs here, at build time, never in the visitor's browser; the page only scales
// and positions the finished drawings, drawing each from its placed geometry (renderPrims). Every
// tree is checked: no stroke crosses another, and the shipped geometry redraws the tree exactly.
//   node scripts/make_grove.mjs           # write
//   node scripts/make_grove.mjs --check   # fail if the committed file is stale or a tree is not clean
// (Node 24 runs the TypeScript module directly.)
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const { birchGroups, buildBirch, crossings, renderPrims } = await import(join(web, "src", "birch.ts"));
const SRC = join(web, "public", "examples", "overview-tree.json"), OUT = join(web, "public", "examples", "grove.json");

const REF = 640;            // the tallest front tree's height, in the drawing's own units
const BACK = 0.74;          // the back row's height, relative to the front's for the same Sharpe
const CROWN = 0.75;         // desktop crowns: narrow enough that four front trees fill the grove's height
const PHONE = { height: 260, crown: 2.4, count: 2 };   // the phone's own grove: two larger trees

const tree = JSON.parse(readFileSync(SRC, "utf8"));
const stems = [...new Set(tree.moves.map((m) => m.stem))].sort((a, b) => a - b);
const movesOf = (s) => tree.moves.filter((m) => m.stem === s);
const best = new Map(stems.map((s) => [s, Math.max(...movesOf(s).flatMap((m) => m.candidates.map((c) => c.sharpe)))]));
const top = Math.max(...best.values());
const evals = (s) => movesOf(s).reduce((n, m) => n + m.candidates.length, 0);

const r1 = (d) => d.replace(/-?\d+\.\d+/g, (x) => (Math.round(Number(x) * 10) / 10).toString());
const bad = [];
function draw(stem, height, opts = {}) {
  const b = buildBirch({ height, groups: birchGroups(movesOf(stem)), seed: stem + 1, attempts: 40, ...opts });
  const c = crossings(b).total;
  if (c) bad.push(`stem ${stem} at ${height.toFixed(0)}: ${c} crossings`);
  const again = renderPrims(b.prims);
  if (again.branches !== b.branches || again.twigs !== b.twigs) bad.push(`stem ${stem}: the placed geometry does not redraw the tree`);
  const n = (v, d = 1) => Math.round(v * 10 ** d) / 10 ** d;
  return {
    stem, back: !!opts.back, height: n(height),
    l: Math.floor(b.l), r: Math.ceil(b.r), top: Math.floor(b.top),
    trunk: r1(b.trunk), bark: r1(b.bark),
    prims: {
      k: b.prims.k,
      branches: b.prims.branches.map((x) => ({ p: x.p.map((v) => n(v)), a: n(x.a, 2), e: n(x.e, 2) })),
      twigs: b.prims.twigs.map((t) => t.map((v) => n(v))),
      leaves: b.prims.leaves.map(([x, y, a, sz, t]) => [n(x), n(y), n(a, 3), n(sz, 2), t]),
    },
  };
}

// desktop: every restart, in search order; the even ones in front, the odd ones a row behind
const desktop = stems.map((s, i) => draw(s, (i % 2 ? BACK : 1) * REF * best.get(s) / top, { back: i % 2 === 1, crown: CROWN }));
// phone: the restarts with the best Sharpe (ties to the earlier), larger and with wider crowns
const phoneStems = stems.slice().sort((a, b) => best.get(b) - best.get(a) || a - b).slice(0, PHONE.count).sort((a, b) => a - b);
const phone = phoneStems.map((s) => draw(s, PHONE.height * best.get(s) / top, { crown: PHONE.crown }));

const out = JSON.stringify({
  note: "Generated by scripts/make_grove.mjs from overview-tree.json; do not edit.",
  restarts: stems.length, evaluations: stems.reduce((n, s) => n + evals(s), 0),
  phone_evaluations: phoneStems.reduce((n, s) => n + evals(s), 0),
  desktop, phone,
}) + "\n";

if (bad.length) { console.error("trees with crossings:\n  " + bad.join("\n  ")); process.exit(1); }
if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== out) { console.error("public/examples/grove.json is stale: run node scripts/make_grove.mjs"); process.exit(1); }
  console.log(`grove.json is current: ${desktop.length} + ${phone.length} trees, no crossings`);
} else {
  writeFileSync(OUT, out);
  console.log(`wrote grove.json: ${desktop.length} desktop + ${phone.length} phone trees (stems ${phoneStems.join(", ")}), ${(out.length / 1024).toFixed(0)} KB, no crossings`);
}
